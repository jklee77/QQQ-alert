def create_comment(score, grade):


    if score >= 90:

        return (
            "현재 QQQ 시장 환경은 매우 우호적입니다. "
            "기술적 상승 추세와 거시 환경이 모두 긍정적이며 "
            "적극적인 분할매수를 고려할 수 있습니다."
        )


    elif score >= 80:

        return (
            "QQQ 상승 추세가 유지되고 있습니다. "
            "금리와 시장 심리를 확인하면서 "
            "분할매수 전략이 유효합니다."
        )


    elif score >= 70:

        return (
            "시장 환경은 양호하지만 일부 위험 요소가 존재합니다. "
            "한 번에 투자하기보다 단계적 접근을 권장합니다."
        )


    elif score >= 60:

        return (
            "시장 방향은 중립입니다. "
            "신규 매수보다는 기존 보유 관리와 "
            "추가 매수 시점 확인이 필요합니다."
        )


    else:

        return (
            "현재 시장 위험도가 높습니다. "
            "현금 비중을 유지하고 "
            "추세 회복 확인이 필요합니다."
        )
